/**
 * The LED colour to send for a team brand colour. Accepts 0xRRGGBB or
 * 0xAARRGGBB (alpha ignored). Unknown colours are returned unchanged.
 */
export function teamLedRgb(brandRgbOrArgb: number): number[] {
  const rgb = brandRgbOrArgb & 0xffffff;
  const led = TEAM_LED_RGB.get(rgb);
  if (led) return [led[0], led[1], led[2]];
  return [(rgb >> 16) & 0xff, (rgb >> 8) & 0xff, rgb & 0xff];
}
